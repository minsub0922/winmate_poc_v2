_cache = {}


def _img(addr):
    pack, k = addr.split('#')
    fn = STATIC + pack
    if fn not in _cache:
        _cache[fn] = json.load(open(fn))['images']
    s = _cache[fn][int(k)]
    return Image.open(io.BytesIO(base64.b64decode(s.split(',', 1)[1])))


_DB = None


def db():
    global _DB
    if _DB is None:
        cat = json.load(open(ROOT + '/app/data/catalog.json'))
        pdb = json.load(open(ROOT + '/app/data/products_db.json'))
        _DB = {p['id']: p for p in cat['products'] + pdb['products']}
    return _DB


def best_gallery(pid):
    """best product cut among the gallery: transparent background first, then the largest"""
    p = db().get(pid) or {}
    best, score = None, -1
    for a in (p.get('gal') or [])[:3]:
        try:
            im = _img(a)
        except Exception:
            continue
        w, h = im.size
        corner = im.convert('RGBA').getpixel((1, 1))[3]
        sc = w * h * (2 if corner < 20 else 1)
        if min(w, h) < 120: sc *= 0.3
        if sc > score: best, score = a, sc
    return best or p.get('th')


