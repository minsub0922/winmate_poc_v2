import assert from 'node:assert/strict';
import fs from 'node:fs';
import { CATS, CRITERIA, CR, REVIEW_CRITERIA_VERSION, criteriaForReview, normalizeCriteriaIds, normalizeReviewOverrides } from '../web/src/domain/review/criteria.js';
import { configureBootstrap } from '../web/src/api/bootstrap.js';
const read = n => JSON.parse(fs.readFileSync(new URL('../data/' + n + '.json', import.meta.url)));
configureBootstrap({ catalog: read('catalog'), products: read('products_db'), images: read('images') });
const { aggregate } = await import('../web/src/domain/review/analyze.js');
assert.equal(REVIEW_CRITERIA_VERSION, 5); assert.equal(CATS.length, 4); assert.equal(CRITERIA.length, 24);
const expected=JSON.parse(fs.readFileSync(new URL('./fixtures/review-criteria-v3.json',import.meta.url))).categories;
assert.deepEqual(CATS.map(c=>({name:c.name,criteria:CRITERIA.filter(x=>x.cat===c.id).map(x=>x.name)})),expected);
assert.equal(CATS.reduce((s, c) => s + c.w, 0), 100);
assert.ok(CATS.every(c=>c.w===25)); assert.ok(CRITERIA.every(c=>c.w===1));
assert.equal(CR.MK3, undefined); assert.equal(CR.DQ2.name,'근거 데이터의 최신성과 출처 명시');
assert.deepEqual(normalizeCriteriaIds(['DS3','DS4','WR3','PR5','MK3'],1), ['DQ5','PR2','DQ2']);
assert.deepEqual(normalizeReviewOverrides({ DS3: false, DS4: true, MK3: true },1), { DQ5: true, DQ2: true });
assert.deepEqual(normalizeCriteriaIds(['CU2','PR3','VS2','DQ1'],2),['CU5','PR1','PR4','VS2','VS3','DQ5']);
assert.deepEqual(normalizeCriteriaIds(['CU2','PR3','VS2','DQ1']),['CU2','PR3','VS2','DQ1']);
assert.deepEqual(normalizeReviewOverrides({DQ1:false,DQ2:true},2),{DQ5:true});
assert.equal(criteriaForReview({}).CRITERIA.length, 54);
assert.equal(criteriaForReview({ criteriaVersion: 2 }).CRITERIA.length, 26);
assert.equal(criteriaForReview({ criteriaVersion: 3 }).CRITERIA.length, 24);
assert.equal(criteriaForReview({ criteriaVersion: 3 }).scoring, undefined);
assert.equal(criteriaForReview({ criteriaVersion: 4 }).scoring.checkpoint_count,4);
assert.deepEqual(normalizeCriteriaIds(['CU2','DQ1'],3),['CU2','DQ1']);
const a = aggregate([{id:'CU1',applied:true},{id:'DQ1',applied:true},{id:'MK3',applied:true}], { CU1: {score:100}, DQ1: {score:0}, MK3: {score:100} });
assert.equal(a.overall, 50); assert.equal(a.nApplied, 2);
const old = aggregate([{id:'CU1',applied:true},{id:'DS4',applied:true}], { CU1:{score:100},DS4:{score:0} }, criteriaForReview({}));
assert.equal(old.overall, 53);
const v2=aggregate([{id:'CU1',applied:true},{id:'DQ1',applied:true}],{CU1:{score:100},DQ1:{score:0}},criteriaForReview({criteriaVersion:2}));
assert.equal(v2.overall,36);
for (const c of CRITERIA) assert.doesNotThrow(() => c.when({kind:'txt',units:1}));
console.log('PASS requested 4/24 labels, equal weights, source check restored, version-aware rerun selection and original v1/v2 scores');

assert.equal(criteriaForReview({criteriaVersion:4}).scoring.level_points,undefined);
assert.deepEqual(criteriaForReview({criteriaVersion:5}).scoring.level_points,{'0':0,'1':40,'2':65,'3':85,'4':100});
assert.deepEqual(normalizeCriteriaIds(['CU2','DQ1'],4),['CU2','DQ1']);
