// 목록 미리보기 메타데이터 — 첫 장부터 덱 순서대로 최대 PREVIEW_N장(3). Best Scenario 목록의 한 줄에 이 장들이 크게 보인다.
// { f: 레이아웃, role: 이 장의 역할, k: 0부터 장 번호(채운 값 · 배경 사진 조회용), page: 1부터, stage: 단계 키, stageName: 단계 이름 }
export const PREVIEW_N = 3;
export const previewOf = (s, n = PREVIEW_N) => slidesOfScenario(s).slice(0, n)
  .map((x, k) => ({ f: x.f, role: x.role, k, page: k + 1, stage: x.stage.key, stageName: x.stage.name }));
for (const s of SCENARIOS) s.preview = previewOf(s);

/** Four sheets that stand for the whole deck — explicit picks, else one visual slide from four evenly spaced middle stages. */
export function repsOf(s) {
  const all = slidesOfScenario(s);
  const pageOf = (f) => all.findIndex((x) => x.f === f) + 1;
  if (REPS[s.id]) return REPS[s.id].map((f) => ({ ...all[pageOf(f) - 1], page: pageOf(f) }));
  const mid = s.flow.filter((g) => g.key !== 'open' && g.key !== 'close');
  const pick = [0, 1, 2, 3].map((i) => mid[Math.round((i * (mid.length - 1)) / 3)]).filter((g, i, a) => g && a.indexOf(g) === i);
  return pick.map((g) => { const x = g.slides[0]; return { ...x, stage: g, page: pageOf(x.f) }; }).slice(0, 4);
}
