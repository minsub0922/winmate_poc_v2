// A criterion added later without an entry above still gets a usable label:
// the first phrase of its name, before particles and separators.
const fallback = name => {
  const head = name.split(/\s*[·,(]\s*|의\s|과\s|와\s/)[0].trim() || name;
  return [...head].length > 7 ? [...head].slice(0, 6).join('') + '…' : head;
};

export const criterionShortName = c => c.short || SHORT[c.name] || fallback(c.name);

// Labels for one rubric, unique across all of its criteria.
export function criterionShortNames(criteria) {
  const out = {}, seen = new Map();
  for (const c of criteria) {
    let label = criterionShortName(c);
    if (seen.has(label)) label = `${label} ${c.id}`;
    seen.set(label, c.id); out[c.id] = label;
  }
  return out;
}
