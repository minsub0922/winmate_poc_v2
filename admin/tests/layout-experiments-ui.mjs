// Real isolated server: admin/tests/fixtures/layout_cleanup_server.py (no AI mocks).
import { chromium } from '../../app/web/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
const base = process.env.WINMATE_ADMIN_TEST_URL || 'http://127.0.0.1:8799';
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1512, height: 1050 } });
  await context.request.post(base + '/api/auth/login', { data: { username: 'admin', password: 'layout-cleanup-isolated-password' } });
  const page = await context.newPage(), errors = [], writes = [], runs = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (r.method() !== 'GET') writes.push(r.url()); });
  page.on('request', r => { if (r.url().endsWith('/experiments/run')) runs.push(r.postDataJSON()); });
  await page.goto(base + '/admin/layout-library');
  await page.locator('.ll-card').first().waitFor();
  await page.getByLabel('레이아웃 검색', { exact: true }).fill('L_VS_DSS_FB');
  await page.locator('.ll-card[data-layout="L_VS_DSS_FB"] .ll-card-open').click();
  const detail = page.getByRole('dialog').filter({ has: page.locator('.ll-detail') });
  const button = detail.getByRole('button', { name: '실험하기', exact: true });
  const footer = await detail.locator('.modal-footer').boundingBox(), bb = await button.boundingBox();
  assert.ok(Math.abs(bb.x + bb.width / 2 - footer.x - footer.width / 2) < 3);
  await page.waitForFunction(() => Object.entries(localStorage).filter(([k]) => k.includes('activity-outbox')).every(([,v]) => JSON.parse(v).length === 0));
  const storageBefore = await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } }));
  writes.length = 0;
  await button.click();
  const dialog = page.getByRole('dialog').filter({ has: page.locator('.le-workspace') });
  await dialog.locator('.lf-flow').waitFor();
  assert.equal(runs.length, 0, 'opening the experiment must not execute it');
  assert.equal(await dialog.locator('.le-output iframe').count(), 0);
  const left = await dialog.locator('.le-left').boundingBox(), right = await dialog.locator('.le-output').boundingBox();
  assert.ok(left.x + left.width < right.x);
  assert.ok(await dialog.locator('.lf-flow').isVisible());
  const graph = await dialog.locator('.lf-flow').boundingBox();
  assert.ok(graph.height > left.height * .9);
  assert.equal(await dialog.getByLabel('샘플 입력 편집').count(), 0);
  assert.equal(await dialog.getByLabel('단계 추가', { exact: true }).count(), 0);
  const picker = dialog.getByRole('button', { name: '실험 입력 선택', exact: true });
  await picker.click();
  await dialog.locator('.le-samples>div').last().waitFor();
  assert.equal(await dialog.locator('.le-samples>div').count(), 5);
  assert.equal((await dialog.locator('.lf-flow').boundingBox()).height, graph.height);
  await dialog.getByRole('button', { name: /2\. 기존 환경 개선/ }).click();
  const editor = dialog.getByLabel('샘플 입력 편집');
  const input = JSON.parse(await editor.inputValue());
  input.customer_name = '저장하지 않는 고객명';
  await editor.fill(JSON.stringify(input, null, 2));
  assert.equal(runs.length, 0, 'selecting or editing inputs must not execute them');
  await dialog.getByRole('button', { name: '선택한 샘플 동시 실행' }).click();
  assert.equal(await dialog.locator('.le-input-pop').count(), 0);
  await picker.click();
  await page.waitForFunction(() => [...document.querySelectorAll('.le-samples small')].filter(n => n.textContent === '완료').length === 5);
  assert.equal(runs.length, 5);
  assert.ok(runs.some(r => r.input.customer_name === '저장하지 않는 고객명'));
  await dialog.getByLabel('실험 업종').selectOption('HT');
  await page.waitForFunction(() => {
    const editor = document.querySelector('.le-editor');
    return editor && JSON.parse(editor.value).industry === 'HT';
  });
  assert.equal(JSON.parse(await editor.inputValue()).industry, 'HT');
  assert.equal(runs.length, 5, 'switching to a new industry must only prepare inputs');
  assert.equal(await dialog.locator('.le-output iframe').count(), 0);
  await dialog.getByRole('button', { name: '이 입력 실행', exact: true }).click();
  await dialog.locator('.le-output iframe').waitFor();
  assert.equal(runs.length, 6);
  assert.equal(runs.at(-1).input.industry, 'HT');
  await picker.click();
  await dialog.getByLabel('실험 업종').selectOption('FB');
  await dialog.getByRole('button', { name: /2\. 기존 환경 개선/ }).click();
  assert.equal(JSON.parse(await editor.inputValue()).customer_name, '저장하지 않는 고객명');
  assert.equal(runs.length, 6, 'switching back must not rerun completed samples');
  if (process.env.WINMATE_EXPERIMENT_SCREENSHOT) await page.screenshot({ path: process.env.WINMATE_EXPERIMENT_SCREENSHOT.replace('.png', '-popup.png') });
  await page.keyboard.press('Escape');
  assert.ok(await dialog.isVisible());
  assert.equal(await dialog.locator('.le-input-pop').count(), 0);
  assert.ok(await picker.evaluate(el => el === document.activeElement));
  if (process.env.WINMATE_EXPERIMENT_SCREENSHOT) await page.screenshot({ path: process.env.WINMATE_EXPERIMENT_SCREENSHOT });
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.le-workspace').count(), 0);
  assert.ok(await detail.isVisible());
  await button.click();
  await dialog.locator('.lf-flow').waitFor();
  assert.equal(runs.length, 6, 'reopening must not execute samples');
  await picker.click();
  assert.equal(JSON.parse(await page.getByLabel('샘플 입력 편집').inputValue()).customer_name, '샘플 고객 1');
  await page.locator('.le-result-head').click();
  assert.equal(await dialog.locator('.le-input-pop').count(), 0);
  // Hold a real request before delivery to exercise AbortController without a
  // fabricated model response or a slow paid generation.
  let release;
  await page.route('**/experiments/run', async route => {
    await new Promise(resolve => { release = resolve; });
    await route.continue().catch(() => {});
  }, { times: 1 });
  await page.getByRole('button', { name: '이 입력 실행', exact: true }).click();
  await page.getByRole('button', { name: '실행 취소', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.le-result-head>span')?.textContent === '취소됨');
  release?.();
  await page.getByRole('button', { name: '이 입력 실행', exact: true }).click();
  await page.locator('.le-output iframe').waitFor();
  const storageAfter = await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } }));
  assert.deepEqual(storageBefore, storageAfter);
  assert.ok(writes.every(u => /\/experiments\/(samples|run)$/.test(u)), writes.join('\n'));
  assert.deepEqual(errors, []);
  console.log('✓ explicit execution only, no auto-fill on open/edit/industry change, parallel runs, cancellation/retry, compact dropdown, no storage writes');
} finally { await browser.close(); }
