# presetShapeDefinitions.xml (ECMA-376 · Apache POI copy, Apache-2.0) → src/my/presets.js (compact JSON)
# per shape: { av: [[name, fmla]], gd: [[name, fmla]], p: [{ w, h, f: fill mode, s: stroke(0/1), c: [[op, ...args]] }], r: [l, t, r, b] }
import sys, json, xml.etree.ElementTree as ET
src, out = sys.argv[1], sys.argv[2]
A = '{http://schemas.openxmlformats.org/drawingml/2006/main}'
root = ET.parse(src).getroot()
res = {}
def pt(e): return [e.get('x'), e.get('y')]
for shp in root:
    d = {}
    av = shp.find(A + 'avLst'); gd = shp.find(A + 'gdLst')
    if av is not None and len(av): d['av'] = [[g.get('name'), g.get('fmla')] for g in av]
    if gd is not None and len(gd): d['gd'] = [[g.get('name'), g.get('fmla')] for g in gd]
    rect = shp.find(A + 'rect')
    if rect is not None: d['r'] = [rect.get('l'), rect.get('t'), rect.get('r'), rect.get('b')]
    paths = []
    pl = shp.find(A + 'pathLst')
    for p in (pl if pl is not None else []):
        q = {}
        if p.get('w'): q['w'] = int(p.get('w'))
        if p.get('h'): q['h'] = int(p.get('h'))
        if p.get('fill') and p.get('fill') != 'norm': q['f'] = p.get('fill')
        if p.get('stroke') in ('false', '0'): q['s'] = 0
        cmds = []
        for c in p:
            t = c.tag.replace(A, '')
            if t == 'moveTo': cmds.append(['M'] + pt(c[0]))
            elif t == 'lnTo': cmds.append(['L'] + pt(c[0]))
            elif t == 'arcTo': cmds.append(['A', c.get('wR'), c.get('hR'), c.get('stAng'), c.get('swAng')])
            elif t == 'quadBezTo': cmds.append(['Q'] + pt(c[0]) + pt(c[1]))
            elif t == 'cubicBezTo': cmds.append(['C'] + pt(c[0]) + pt(c[1]) + pt(c[2]))
            elif t == 'close': cmds.append(['Z'])
        q['c'] = cmds
        paths.append(q)
    d['p'] = paths
    res[shp.tag] = d
js = '// Preset shape geometry — ECMA-376 presetShapeDefinitions (via Apache POI, Apache-2.0). Generated by build/my/presets.py — do not edit.\n'
js += 'export const PRESETS = JSON.parse(' + json.dumps(json.dumps(res, separators=(',', ':'), ensure_ascii=False)) + ');\n'
open(out, 'w').write(js)
print(len(res), 'shapes', len(js), 'bytes')
